#!/usr/bin/env python3
"""Generate matching chart colors for Web and Swift from documented source palettes."""
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
palettes = json.loads((ROOT / 'docs/chart-palettes.json').read_text(encoding='utf-8'))

def rgb(hex_value):
    return [int(hex_value[i:i+2], 16) for i in (0, 2, 4)]

def luminance(channels):
    values = [v / 255 for v in channels]
    return sum((v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4) * w
               for v, w in zip(values, [.2126, .7152, .0722]))

def contrast(a, b):
    a, b = luminance(a), luminance(b)
    return (max(a, b) + .05) / (min(a, b) + .05)

def mix(a, b, amount):
    return [math.floor(x + (y - x) * amount + .5) for x, y in zip(a, b)]

def variant(hex_value, dark, level):
    color = rgb(hex_value)
    # High mode meets 3:1 even on the conservative tinted chart surfaces.
    # Low mode is a deliberate softer fill; labels retain the UI text color.
    background = rgb(('2e3a52' if dark else 'e1e8f6') if level == 'high' else ('29292e' if dark else 'ffffff'))
    target = 3.2 if level == 'high' else 2.2
    if level == 'high' and contrast(color, background) >= target:
        return hex_value
    destination = ([255]*3 if dark else [0]*3) if contrast(color, background) < target else background
    low, high = 0., 1.
    strengthening = contrast(color, background) < target
    for _ in range(24):
        mid = (low + high) / 2
        if (contrast(mix(color, destination, mid), background) < target) == strengthening:
            low = mid
        else:
            high = mid
    result = mix(color, destination, high)
    return ''.join(f'{v:02x}' for v in result)

for palette in palettes:
    assert len(set(palette['colors'])) == len(palette['colors'])
    palette['variants'] = {f'{theme}-{level}': [variant(c, theme == 'dark', level) for c in palette['colors']]
                           for theme in ['light', 'dark'] for level in ['high', 'low']}

web = '/* Generated by scripts/sync-chart-palettes.py; edit docs/chart-palettes.json. */\n'
web += 'window.AieyesChartPalettes = ' + json.dumps(palettes, ensure_ascii=False, indent=2) + ';\n'
swift = '// BEGIN GENERATED CHART PALETTES\n'
swift += '    struct ChartPreset {\n        let id: String, name: String\n        let lightHigh, lightLow, darkHigh, darkLow: [UInt32]\n'
swift += '        func colors(dark: Bool, contrast: String) -> [UInt32] {\n            dark ? (contrast == "low" ? darkLow : darkHigh) : (contrast == "low" ? lightLow : lightHigh)\n        }\n    }\n'
swift += '    static let chartPresets: [ChartPreset] = [\n'
for palette in palettes:
    swift += f'        ChartPreset(id: "{palette["id"]}", name: "{palette["name"]}",\n'
    swift += ',\n'.join('            ' + name + ': [' + ', '.join('0x' + c for c in palette['variants'][key]) + ']'
                        for name, key in [('lightHigh', 'light-high'), ('lightLow', 'light-low'), ('darkHigh', 'dark-high'), ('darkLow', 'dark-low')]) + '),\n'
swift += '    ]\n    // END GENERATED CHART PALETTES'
path = ROOT / 'apps/macos/Sources/Aieyes/Palette.swift'
old = path.read_text(encoding='utf-8')
start, end = '// BEGIN GENERATED CHART PALETTES', '// END GENERATED CHART PALETTES'
if start in old:
    a, b = old.index(start), old.index(end) + len(end)
    updated = old[:a] + swift + old[b:]
else:
    updated = old.replace('enum Palette {', 'enum Palette {\n    ' + swift)
outputs = {ROOT / 'apps/desktop/web/chart-palettes.js': web, path: updated}
for path, value in outputs.items():
    if '--check' in sys.argv:
        assert path.read_text(encoding='utf-8') == value, f'Stale chart palettes: {path}; run scripts/sync-chart-palettes.py'
    else:
        path.write_text(value, encoding='utf-8')
print('Chart palettes: five families × light/dark × high/low are synchronized')
