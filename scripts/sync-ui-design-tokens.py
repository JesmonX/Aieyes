#!/usr/bin/env python3
"""Generate native Swift / Web CSS design tokens; --check never writes files."""
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/ui-design-tokens.json'
BEGIN = '/* BEGIN GENERATED UI DESIGN TOKENS */'
END = '/* END GENERATED UI DESIGN TOKENS */'


def camel(name):
    first, *rest = name.split('-')
    return first + ''.join(part.title() for part in rest)


def outputs():
    table = json.loads(SOURCE.read_text(encoding='utf-8'))
    assert table['version'] == 1, 'Unsupported design token version'
    names = set()
    for group in ('dimensions', 'numbers', 'colors', 'aliases'):
        for name in table[group]:
            assert re.fullmatch(r'[a-z]+(?:-[a-z]+)*', name), f'Invalid token: {name}'
            assert name not in names, f'Duplicate token: {name}'
            names.add(name)
    css = [BEGIN, '/* Generated by scripts/sync-ui-design-tokens.py; edit docs/ui-design-tokens.json. */', ':root {']
    swift = ['// Generated by scripts/sync-ui-design-tokens.py; edit docs/ui-design-tokens.json.',
             'import SwiftUI', '', 'enum DesignTokens {']
    # Platform geometry and font weights need not change the native macOS output:
    # a web override replaces the shared value in the CSS, so each property is emitted once.
    web = table.get('web', {})
    web_dimensions, web_weights = web.get('dimensions', {}), web.get('weights', {})
    for name, value in web_dimensions.items():
        assert name in table['dimensions'] and isinstance(value, (int, float)) and value >= 0
    for name, value in web_weights.items():
        assert name in table['weights'] and value in (400, 500, 600, 700)
    for group, unit, native_type in [('dimensions', 'px', 'CGFloat'), ('numbers', '', 'Double')]:
        for name, value in table[group].items():
            assert isinstance(value, (int, float)) and value >= 0, f'Invalid metric: {name}'
            web_value = web_dimensions.get(name, value) if group == 'dimensions' else value
            css.append(f'  --{name}: {web_value}{unit};')
            swift.append(f'    static let {camel(name)}: {native_type} = {value}')
    for name, weight in table['weights'].items():
        assert weight['swift'] in ('regular', 'medium', 'semibold', 'bold')
        assert weight['web'] in (400, 500, 600, 700)
        css.append(f'  --weight-{name}: {web_weights.get(name, weight["web"])};')
        swift.append(f'    static let weight{name.title()}: Font.Weight = .{weight["swift"]}')
    # Shared motion durations (milliseconds); curves stay platform-native.
    for name, value in table.get('motion', {}).items():
        assert re.fullmatch(r'[a-z]+', name) and isinstance(value, int) and 0 < value <= 1000, f'Invalid motion: {name}'
        css.append(f'  --motion-{name}: {value}ms;')
        swift.append(f'    static let motion{name.title()}: Double = {value / 1000}')
    for name, target in table['aliases'].items():
        assert target in table['dimensions'], f'Unknown alias target: {target}'
        css.append(f'  --{name}: var(--{target});')
        swift.append(f'    static let {camel(name)} = {camel(target)}')
    for theme in ('light', 'dark'):
        if theme == 'dark':
            css.extend(['}', ':root[data-theme=dark] {'])
        for name, variants in table['colors'].items():
            color = variants[theme]
            assert re.fullmatch(r'[0-9a-f]{6}', color), f'Invalid color: {name}'
            css.append(f'  --{name}: #{color};')
            swift.append(f'    static let {camel(name)}{theme.title()}: UInt32 = 0x{color}')
    css.append('}')
    css.append(END)
    swift.extend(['}', ''])
    path = ROOT / 'apps/desktop/web/tokens.css'
    old = path.read_text(encoding='utf-8')
    generated = '\n'.join(css)
    if BEGIN in old:
        updated = old[:old.index(BEGIN)] + generated + old[old.index(END) + len(END):]
    else:
        # Keep generation before platform, accent and accessibility overrides.
        marker = ':root[data-accent=blue]'
        assert marker in old, 'Missing token insertion point'
        updated = old.replace(marker, generated + '\n\n' + marker, 1)
    return {path: updated, ROOT / 'apps/macos/Sources/Aieyes/DesignTokens.swift': '\n'.join(swift)}


if __name__ == '__main__':
    assert sys.argv[1:] in ([], ['--check']), 'Usage: sync-ui-design-tokens.py [--check]'
    stale = []
    for path, value in outputs().items():
        if '--check' in sys.argv:
            if not path.exists() or path.read_text(encoding='utf-8') != value:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(value, encoding='utf-8')
    if stale:
        raise SystemExit('Run python3 scripts/sync-ui-design-tokens.py; stale outputs: ' + ', '.join(stale))
    print('UI design tokens: Swift and CSS are synchronized')
