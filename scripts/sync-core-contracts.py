#!/usr/bin/env python3
"""Generate core/Web/Swift contracts. Edit docs/core-contracts.json, then run this script."""
import json
from pathlib import Path
import sys
import re
import hashlib

root = Path(__file__).resolve().parents[1]
source = (root / 'docs/core-contracts.json').read_text(encoding='utf-8')
table = json.loads(source)
contract_hash = hashlib.sha256(source.encode('utf-8')).hexdigest()
q = lambda value: json.dumps(value, ensure_ascii=False)
array = lambda values: '[' + ', '.join(q(v) for v in values) + ']'
providers, methods = table['providers'], table['methods']
pet_frames = table['petFrameDurations']
assert len(pet_frames) == 9 and all(1 <= len(row) <= 8 and all(isinstance(ms, int) and ms > 0 for ms in row) for row in pet_frames)
assert len({m['name'] for m in methods}) == len(methods), 'Duplicate RPC method'
assert all(m['lane'] in ('main', 'hosts', 'network', 'configuration', 'accounts', 'dashboard', 'quotas', 'wakeups') for m in methods)
names = {m['name'] for m in methods}
for directory, pattern in [('apps/desktop/web', r'\bapi\(\s*[\'\"]([^\'\"]+)[\'\"]'), ('apps/macos/Sources/Aieyes', r'\b(?:engine|client|queries|configuration|networkEngine|metricsEngine|sessionEngine)\.call\(\s*\"([^\"]+)\"')]:
    for path in (root / directory).glob('*'):
        if path.suffix not in ('.js', '.swift'): continue
        for name in re.findall(pattern, path.read_text(encoding='utf-8')):
            if not name.endswith('.') and ('.' in name or name in ('hello', 'dashboard')):
                assert name in names, f'RPC method absent from contract: {name} ({path})'
header = '// Generated by scripts/sync-core-contracts.py; edit docs/core-contracts.json.\n'
rust = header + '''use serde::Serialize;
#[derive(Debug, Clone, Copy, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub enum Lane { Main, Hosts, Network, Configuration, Accounts, Dashboard, Quotas, Wakeups }
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Method {
    pub name: &'static str,
    pub lane: Lane,
    pub update_behavior: &'static str,
    pub invalidates: &'static [&'static str],
    pub invalidate_on_failure: bool,
    pub refresh_key: Option<&'static str>,
}
#[derive(Debug)]
pub struct Provider {
    pub id: &'static str,
    pub name: &'static str,
    pub default_path: &'static str,
    pub binary: &'static str,
    pub requires_path: bool,
    pub wakeup: bool,
    pub discover_local: bool,
    pub agent_id: &'static str,
}
'''
rust += '#[rustfmt::skip]\npub const METHODS: &[Method] = &[\n'
for m in methods:
    key = 'None' if m['refreshKey'] is None else f'Some({q(m["refreshKey"])})'
    rust += f'    Method {{ name: {q(m["name"])}, lane: Lane::{m["lane"].title()}, update_behavior: {q(m["updateBehavior"])}, invalidates: &{array(m["invalidates"])}, invalidate_on_failure: {str(m["invalidateOnFailure"]).lower()}, refresh_key: {key} }},\n'
rust += '];\n#[rustfmt::skip]\npub const PROVIDERS: &[Provider] = &[\n'
for p in providers:
    fields = ', '.join(f'{k}: {q(p[v])}' for k, v in [('id','id'),('name','name'),('default_path','defaultPath'),('binary','binary')])
    fields += ', ' + ', '.join(f'{k}: {str(p[v]).lower()}' for k, v in [('requires_path','requiresPath'),('wakeup','wakeup'),('discover_local','discoverLocal')])
    fields += f', agent_id: {q(p.get("agent", p["id"]))}'
    rust += f'    Provider {{ {fields} }},\n'
rust += '];\n'
for name, values in [('PROVIDER_IDS',[p['id'] for p in providers]),('EXCLUDED_FS_TYPES',table['filesystems']['excludedTypes']),('EXCLUDED_FS_PATHS',table['filesystems']['excludedPaths'])]:
    rust += f'#[rustfmt::skip]\npub const {name}: &[&str] = &{array(values)};\n'
rust += f'pub const FIVE_HOUR_MINUTES: i64 = {table["windows"]["fiveHour"]};\npub const WEEK_MINUTES: i64 = {table["windows"]["week"]};\n'
rust += '#[rustfmt::skip]\npub const PET_FRAME_DURATIONS: &[&[u64]] = &[\n' + ''.join(f'    &{array(row)},\n' for row in pet_frames) + '];\n'
rust += f'pub const CONTRACT_HASH: &str = {q(contract_hash)};\n'
rust += '''pub fn method(name: &str) -> Option<&'static Method> {
    METHODS.iter().find(|m| m.name == name)
}
pub fn provider(id: &str) -> Option<&'static Provider> {
    PROVIDERS.iter().find(|p| p.id == id)
}
'''
# Use rustfmt only for declarations/functions; stable table formatting is skipped.
import subprocess
rust = subprocess.run(['rustfmt','--edition','2024'], input=rust, encoding='utf-8', capture_output=True, check=True).stdout
web = dict(providers={p['id']:p['name'] for p in providers}, wakeupProviders=[p['id'] for p in providers if p['wakeup']], defaultPaths={p['id']:p['defaultPath'] for p in providers}, binaries={p['id']:p['binary'] for p in providers}, windows=table['windows'], filesystems=table['filesystems'], methods={m['name']:{k:v for k,v in m.items() if k!='name'} for m in methods})
web['subscriptions'] = {p['id']: p['subscription'] for p in providers if 'subscription' in p}
web['apiGuidance'] = {p['id']: p['apiGuidance'] for p in providers if 'apiGuidance' in p}
web['agentAliases'] = {p['id']: p['agent'] for p in providers if 'agent' in p}
web['agentProviders'] = [p['id'] for p in providers if 'agent' not in p]
web['providerCapabilities'] = {p['id']: p.get('capabilities', []) for p in providers}
web['providerIcons'] = {p['id']: p['icon'] for p in providers if 'icon' in p}
web['contractHash'] = contract_hash
web['petFrameDurations'] = pet_frames
js = header + '(typeof window === "undefined" ? globalThis : window).AieyesContract = ' + json.dumps(web, ensure_ascii=False, indent=2) + ';\n'
begin, end = '// BEGIN GENERATED CORE CONTRACT', '// END GENERATED CORE CONTRACT'
swift = begin + '\n' + header + 'enum CoreContract {\n'
swift += f'    static let contractHash = {q(contract_hash)}\n'
swift += f'    static let providers = {array([p["id"] for p in providers])}\n'
swift += f'    static let wakeupProviders = {array([p["id"] for p in providers if p["wakeup"]])}\n'
swift += f'    static let agentProviders = {array(web["agentProviders"])}\n'
swift += '    static let agentAliases: [String: String] = [' + ', '.join(f'{q(k)}: {q(v)}' for k, v in web['agentAliases'].items()) + ']\n'
swift += '    static let providerCapabilities: [String: Set<String>] = [' + ', '.join(f'{q(k)}: {array(v)}' for k, v in web['providerCapabilities'].items()) + ']\n'
swift += '    static let providerIcons: [String: String] = [' + ', '.join(f'{q(k)}: {q(v["asset"])}' for k, v in web['providerIcons'].items()) + ']\n'
swift += '    static let providerDarkIcons: [String: String] = [' + ', '.join(f'{q(k)}: {q(v["darkAsset"])}' for k, v in web['providerIcons'].items() if 'darkAsset' in v) + ']\n'
swift += f'    static let monochromeIcons: Set<String> = {array([k for k, v in web["providerIcons"].items() if v.get("monochrome")])}\n'
swift += '''    static func agentProvider(_ provider: String) -> String { agentAliases[provider] ?? provider }
    static func sameAgent(_ lhs: String, _ rhs: String) -> Bool { agentProvider(lhs) == agentProvider(rhs) }
    static func supports(_ provider: String, _ feature: String) -> Bool { providerCapabilities[provider]?.contains(feature) == true }
    static func featureProvider(_ provider: String, _ feature: String) -> String? { providers.first { sameAgent($0, provider) && supports($0, feature) } }
'''
for name, key in [('providerNames','name'),('defaultPaths','defaultPath'),('binaries','binary')]:
    swift += f'    static let {name}: [String: String] = [' + ', '.join(f'{q(p["id"])}: {q(p[key])}' for p in providers) + ']\n'
for name, key in [('subscriptionHints', 'hint'), ('subscriptionLoginURLs', 'loginUrl')]:
    swift += f'    static let {name}: [String: String] = [' + ', '.join(f'{q(p["id"])}: {q(p["subscription"][key])}' for p in providers if 'subscription' in p) + ']\n'
swift += '    static let subscriptionModes: [String: [String: String]] = [' + ', '.join(q(p['id']) + ': [' + ', '.join(q(k) + ': ' + q(v) for k, v in p['subscription']['modes'].items()) + ']' for p in providers if 'subscription' in p) + ']\n'
swift += '    static let apiGuidance: [String: [String: String]] = [' + ', '.join(q(p['id']) + ': [' + ', '.join(q(k) + ': ' + q(v) for k, v in p['apiGuidance'].items()) + ']' for p in providers if 'apiGuidance' in p) + ']\n'
swift += f'    static let fiveHourMinutes = {table["windows"]["fiveHour"]}\n    static let weekMinutes = {table["windows"]["week"]}\n'
swift += f'    static let excludedFilesystemTypes: Set<String> = {array(table["filesystems"]["excludedTypes"])}\n    static let excludedFilesystemPaths = {array(table["filesystems"]["excludedPaths"])}\n'
swift += '    static let petFrameDurations: [[Int]] = ' + json.dumps(pet_frames) + '\n'
swift += '    static let methodLanes: [String: String] = [\n' + ''.join(f'        {q(m["name"])}: {q(m["lane"])},\n' for m in methods) + '    ]\n'
swift += '    static let updateBehaviors: [String: String] = [' + ', '.join(f'{q(m["name"])}: {q(m["updateBehavior"])}' for m in methods) + ']\n'
swift += '    static let configurationMethods = Set(methodLanes.filter { $0.value == "configuration" }.keys)\n}\n' + end
path = root / 'apps/macos/Sources/Aieyes/Models.swift'
old = path.read_text(encoding='utf-8')
updated = old[:old.index(begin)] + swift + old[old.index(end)+len(end):] if begin in old else old.rstrip() + '\n\n' + swift + '\n'
outputs = {root/'crates/core/src/contracts.rs':rust, root/'apps/desktop/web/contracts.js':js, path:updated}
for path, content in outputs.items():
    if '--check' in sys.argv:
        assert path.exists() and path.read_text(encoding='utf-8') == content, f'Stale contract: {path}; run scripts/sync-core-contracts.py'
    else:
        path.write_text(content, encoding='utf-8')
print(f'Core/Web/Swift contracts agree ({len(methods)} RPC methods)')
