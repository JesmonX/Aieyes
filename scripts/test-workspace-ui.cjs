    assert.equal(await page.locator('#live-sessions').isVisible(),true);assert.match(await page.locator('#live-sessions summary').textContent(),/等待输入 1/);
    await page.evaluate(()=>renderLiveSessions({sessions:[],sources:[{provider:'codex',machineId:'local',state:'failed',error:'fixture'}]}));
    assert.equal(await page.locator('#session-attention').isVisible(),true,'source failures remain visible while idle');
